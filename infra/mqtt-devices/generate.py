"""Derive the Home Assistant MQTT package and the ble2ha.js device list from devices.yml.

    uv run generate.py          # write outputs
    uv run generate.py --check  # exit 1 if outputs are stale
"""
import re
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
DEVICES = HERE / "devices.yml"
PACKAGE = HERE.parents[1] / "kubernetes/30-apps/home/config/packages/mqtt_devices.yaml"
BLE_SCRIPT = HERE / "shelly_scripts/ble2ha.js"

COMMON = ["name", "unique_id", "state_topic", "value_template", "device_class", "icon", "entity_category"]
PLATFORM_KEYS = {
    "sensor": COMMON + ["state_class", "unit_of_measurement", "suggested_display_precision"],
    "binary_sensor": COMMON,
    "event": COMMON + ["event_types"],
}
BLE_DECODERS = {"Govee": "decoderGovee", "Shelly": "decoderShelly"}
BEGIN, END = "// BEGIN generated by infra/mqtt-devices/generate.py", "// END generated"


class NoAliasDumper(yaml.SafeDumper):
    def ignore_aliases(self, data):
        return True


def slug(name: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def device_info(d: dict) -> dict:
    info = {"identifiers": [d["id"]], "name": d["name"]}
    for key in ("manufacturer", "model", "sw_version"):
        if d.get(key):
            info[key] = d[key]
    if d.get("mac_addr"):
        info["connections"] = [["mac", d["mac_addr"]]]
    return info


def build_package(devices: list[dict]) -> str:
    mqtt: dict[str, list] = {}
    seen: set[str] = set()
    for d in devices:
        default_topic = d.get("state_topic") or f"devices/{d['id']}/state"
        for i, comp in enumerate(d["components"]):
            entity = {
                "state_class": "measurement",
                **comp,
                "unique_id": f"{d['id']}_{slug(comp['name'])}",
                "state_topic": comp.get("state_topic") or default_topic,
            }
            if entity["unique_id"] in seen:
                sys.exit(f"duplicate unique_id {entity['unique_id']}")
            seen.add(entity["unique_id"])
            platform = comp["platform"]
            out = {k: entity[k] for k in PLATFORM_KEYS[platform] if entity.get(k) is not None}
            out["device"] = device_info(d) if i == 0 else {"identifiers": [d["id"]]}
            mqtt.setdefault(platform, []).append(out)
    header = "# Generated by infra/mqtt-devices/generate.py from devices.yml. Do not edit.\n"
    return header + yaml.dump(
        {"mqtt": mqtt}, Dumper=NoAliasDumper, sort_keys=False, allow_unicode=True, width=120
    )


def build_ble_script(devices: list[dict], current: str) -> str:
    rows = [
        f'    {{ id: "{d["id"]}", mac: "{d["mac_addr"]}", decoder: {BLE_DECODERS[d["manufacturer"]]} }},'
        for d in devices
        if d["origin"] == "ble2mqtt"
    ]
    block = "\n".join([BEGIN, "const Devices = [", *rows, "];", END])
    pattern = re.compile(re.escape(BEGIN) + ".*?" + re.escape(END), re.S)
    if not pattern.search(current):
        sys.exit(f"markers not found in {BLE_SCRIPT}")
    return pattern.sub(lambda _: block, current)


def main() -> None:
    devices = yaml.safe_load(DEVICES.read_text())["devices"]
    outputs = {
        PACKAGE: build_package(devices),
        BLE_SCRIPT: build_ble_script(devices, BLE_SCRIPT.read_text()),
    }
    stale = [p for p, text in outputs.items() if not p.exists() or p.read_text() != text]
    if "--check" in sys.argv:
        for p in stale:
            print(f"stale: {p}")
        sys.exit(1 if stale else 0)
    for p in stale:
        p.write_text(outputs[p])
        print(f"wrote {p}")


if __name__ == "__main__":
    main()
